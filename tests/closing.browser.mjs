import { chromium } from 'playwright';
import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';

const project = new URL('../', import.meta.url);
const envText = await readFile(new URL('.env', project), 'utf8');
const env = Object.fromEntries(envText.replace(/^\uFEFF/, '').split(/\r?\n/).filter(l => l.includes('=')).map(l => [l.slice(0, l.indexOf('=')), l.slice(l.indexOf('=') + 1)]));
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1050 }, locale: 'pt-BR' });
const errors = []; page.on('pageerror', e => errors.push(e.message));
try {
  await page.goto('http://127.0.0.1:15173');
  await page.getByLabel('Usuário', { exact: true }).fill(env.APP_ADMIN_USERNAME);
  await page.getByLabel('Senha', { exact: true }).fill(env.APP_ADMIN_PASSWORD);
  await page.getByRole('button', { name: 'Entrar no sistema', exact: true }).click();
  await page.getByText(/Dia .* fechado/, { exact: true }).waitFor();
  const status = await (await page.request.get('http://127.0.0.1:15173/api/v1/closings/status')).json();
  assert.equal(status.closed, true);
  await page.getByRole('navigation').getByRole('button', { name: 'Fechamento', exact: true }).click();
  const older = new Date(status.date + 'T12:00:00Z'); older.setUTCDate(older.getUTCDate() - 2); const olderDay = older.toISOString().slice(0, 10);
  await page.getByLabel('Data inicial', { exact: true }).fill(olderDay);
  await page.getByLabel('Data final', { exact: true }).fill(olderDay);
  await page.getByRole('button', { name: 'Fechar intervalo selecionado', exact: true }).click();
  const confirmation = page.getByRole('dialog');
  assert.equal(await confirmation.getByRole('button', { name: 'Fechar e preservar snapshot', exact: true }).isDisabled(), true);
  await confirmation.getByLabel('Observação do fechamento (opcional)', { exact: true }).fill('Fechamento pela interface de teste');
  await confirmation.getByLabel('Conferi os registros', { exact: false }).check();
  await confirmation.getByRole('button', { name: 'Fechar e preservar snapshot', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  console.log('OK navegador — fechamento de período pela interface com confirmação explícita');
  const closingRow = page.getByRole('row').filter({ hasText: 'Fechamento #' + status.closureId });
  await closingRow.getByRole('button', { name: 'Ver snapshot', exact: true }).click();
  const modal = page.getByRole('dialog');
  await modal.getByText('Snapshot preservado · integridade conferida', { exact: true }).waitFor();
  const hash = await modal.locator('code').innerText(); assert.match(hash, /^[a-f0-9]{64}$/);
  await modal.getByText('Itens das compras', { exact: false }).click();
  const [download] = await Promise.all([page.waitForEvent('download'), modal.getByRole('link', { name: 'Baixar snapshot completo em JSON', exact: true }).click()]);
  const contents = await readFile(await download.path());
  assert.equal(createHash('sha256').update(contents).digest('hex'), hash);
  await page.screenshot({ path: new URL('docs/previews/snapshot.png', project).pathname.replace(/^\//, ''), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  const size = await page.evaluate(() => ({ width: innerWidth, document: document.documentElement.scrollWidth }));
  assert.ok(size.document <= size.width);
  await page.screenshot({ path: new URL('docs/previews/snapshot-mobile.png', project).pathname.replace(/^\//, ''), fullPage: true });
  await modal.getByRole('button', { name: 'Fechar', exact: true }).click();
  await page.getByRole('button', { name: 'Hoje já está fechado', exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Hoje já está fechado', exact: true }).isDisabled(), true);
  await page.getByRole('button', { name: 'Abrir menu', exact: true }).click();
  await page.getByRole('navigation').getByRole('button', { name: 'Vendas', exact: true }).click();
  await page.getByRole('button', { name: 'Nova venda', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: 'Confirmar venda', exact: true }).isDisabled(), true);
  await page.getByRole('dialog').getByText('O dia está fechado.', { exact: false }).waitFor();
  assert.deepEqual(errors, []);
  console.log('OK navegador — banner do dia fechado, snapshot visível, download com SHA-256 correto, layout móvel e bloqueio de novos lançamentos.');
} catch (error) {
  console.error(String(error.stack || error).replaceAll(env.APP_ADMIN_PASSWORD, '[senha omitida]'));
  process.exitCode = 1;
} finally { await browser.close(); }
